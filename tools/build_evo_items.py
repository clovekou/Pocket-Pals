#!/usr/bin/env python3
"""Build evoitems.js: which Pokémon evolve with which evolution item.

Reads tools/pokeapi/pokemon_evolution.csv and pokemon_species.csv (PokéAPI data) and keeps
only evolutions where both Pokémon are in species.js. Output:

    const EVO_ITEMS = { fireStone: [[37, 38, ''], ...], razorClaw: [[215, 461, 'night'], ...] };

Item kinds (used directly vs. held until the next level-up) are defined in game.js ITEMS.
    python3 tools/build_evo_items.py
"""
import csv, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')

# PokéAPI item id -> game item key
ITEM_IDS = {
    82: 'fireStone', 84: 'waterStone', 83: 'thunderStone', 85: 'leafStone', 81: 'moonStone', 80: 'sunStone',
    107: 'shinyStone', 108: 'duskStone', 109: 'dawnStone', 885: 'iceStone', 2160: 'linkingCord',
    1174: 'sweetApple', 1175: 'tartApple', 2109: 'syrupyApple', 1311: 'crackedPot', 1312: 'crackedPot',
    2110: 'unremarkableTeacup', 2111: 'unremarkableTeacup', 2230: 'blackAugurite', 2231: 'peatBlock',
    2232: 'metalAlloy', 2045: 'auspiciousArmor', 1677: 'maliciousArmor',
    198: 'kingsRock', 210: 'metalCoat', 212: 'dragonScale', 229: 'upgrade', 301: 'dubiousDisc', 298: 'protector',
    299: 'electirizer', 300: 'magmarizer', 302: 'reaperCloth', 303: 'razorClaw', 304: 'razorFang', 110: 'ovalStone',
    203: 'deepSeaTooth', 204: 'deepSeaScale', 580: 'prismScale', 687: 'sachet', 686: 'whippedDream',
}
TRADE = '2'          # "Trade or Linking Cord"
SPIN = '5'           # Alcremie's sweets: not used


def main():
    src = open(os.path.join(ROOT, 'species.js'), encoding='utf-8').read()
    roster = set(int(x) for x in re.findall(r'"id":(\d+)', src))
    pre = {int(r['id']): int(r['evolves_from_species_id']) for r in csv.DictReader(open(os.path.join(HERE, 'pokeapi', 'pokemon_species.csv')))
           if r['evolves_from_species_id']}
    out = {}
    for r in csv.DictReader(open(os.path.join(HERE, 'pokeapi', 'pokemon_evolution.csv'))):
        if r['evolution_trigger_id'] == SPIN: continue
        to = int(r['evolved_species_id']); fr = pre.get(to)
        if not fr or fr not in roster or to not in roster: continue
        item = r['trigger_item_id'] or r['held_item_id']
        if item: key = ITEM_IDS.get(int(item))
        elif r['evolution_trigger_id'] == TRADE: key = 'linkingCord'     # trade evolutions without an item
        else: continue
        if not key: continue
        time = r['time_of_day'] if r['time_of_day'] in ('day', 'night') else ''
        if key == 'peatBlock': time = ''                                # (full moon in the games)
        row = [fr, to, time]
        if row not in out.setdefault(key, []): out[key].append(row)
    lines = ['// GENERATED by tools/build_evo_items.py from PokéAPI data. Item key -> [[from, to, "" | "day" | "night"]].',
             'const EVO_ITEMS = {']
    for k in sorted(out):
        lines.append(f'  {k}: {json.dumps(sorted(out[k]))},')
    lines.append('};')
    open(os.path.join(ROOT, 'evoitems.js'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(f'wrote evoitems.js: {len(out)} items, {sum(len(v) for v in out.values())} evolutions')


if __name__ == '__main__':
    main()
